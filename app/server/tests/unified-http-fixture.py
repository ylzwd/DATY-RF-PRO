"""Disposable TLS/SQLite peer for Node host-port integration tests.

Only stdin controls this fixture. It reuses the isolated authenticated Handler
and session from test_unified_api; there is no production API/DB/receiver import.
"""
import json
from pathlib import Path
import sys
import uuid

from test_unified_api import UnifiedApiTests
import unified_database as db


def emit(value):
    print(json.dumps(value, ensure_ascii=True, allow_nan=False), flush=True)


def main():
    if sys.argv[1:] != ['--stdio-fixture']:
        raise SystemExit('Only --stdio-fixture is supported')
    UnifiedApiTests.setUpClass()
    case = UnifiedApiTests(methodName='test_valid_write_read_list_and_receipt')
    try:
        case.setUp()
        # The CA is generated by setUpClass in its exclusive OS temporary folder.
        config = json.loads((case.directory / 'security' / 'tls-config.json').read_text(encoding='utf-8'))
        ca_path = Path(config['ca_file']).resolve()
        if ca_path.parent != (case.directory / 'security').resolve():
            raise RuntimeError('Fixture CA escaped its temporary directory')
        emit({'event':'ready', 'origin':f'https://127.0.0.1:{case.http.server_port}',
              'ca':ca_path.read_text(encoding='ascii'), 'temporary':True,
              'device_commands':0})
        for line in sys.stdin:
            command = json.loads(line)
            name = command.get('command')
            if name == 'shutdown':
                emit({'id':command['id'], 'ok':True})
                break
            if name == 'reset':
                case.setUp()
                result = {'epoch':case.meta['epoch']}
            elif name == 'drop_next_post_reply':
                case.http.drop_reply = True
                result = {'armed':True}
            elif name == 'rotate_epoch':
                # Recovery epoch transition only in the current disposable DB.
                with case.session() as connection:
                    current = db.status(connection)['epoch']
                    new_epoch = uuid.uuid4().hex
                    db.rotate_recovery_epoch(connection, current, new_epoch)
                result = {'previous_epoch':current, 'epoch':new_epoch}
            elif name == 'stats':
                accesses = case.db_accesses
                with case.session() as connection:
                    result = {name:connection.execute('SELECT COUNT(*) FROM '+table).fetchone()[0]
                              for name,table in (
                                  ('resources','db_resources'),('versions','db_resource_versions'),
                                  ('operations','db_operations'),('batches','db_batches'),
                                  ('audit','db_audit'),('device_commands','commands'))}
                    result['foreign_key_errors'] = len(connection.execute('PRAGMA foreign_key_check').fetchall())
                result['db_accesses'] = accesses
                # Diagnostic reads do not count as authenticated API accesses.
                case.db_accesses = accesses
            else:
                raise ValueError('Unsupported fixture command')
            emit({'id':command['id'], 'ok':True, **result})
    finally:
        case.tearDown()
        UnifiedApiTests.tearDownClass()


if __name__ == '__main__':
    main()
