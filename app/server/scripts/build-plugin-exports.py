"""Build allowlisted source ZIPs; no production data, network or device I/O."""
from pathlib import Path, PurePosixPath
import argparse,base64,hashlib,io,json,re,zipfile

def build(root, registry):
    root=Path(root).resolve()
    data=json.loads(Path(registry).read_text('utf-8'))
    if data.get('schema')!='daty-plugin-source-registry-v1':raise ValueError('Unknown registry schema')
    catalog=[];ids=set()
    for item in data['plugins']:
        identity=item['id']
        if not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,63}',identity) or identity in ids:raise ValueError('Invalid/duplicate plugin id')
        ids.add(identity);contents={};hashes={}
        if not item['adapterKeys'] or not all(re.fullmatch(r'[a-z0-9-]+',v) for v in item['adapterKeys']):raise ValueError('Invalid adapter keys')
        for name in item['files']:
            relative=PurePosixPath(name)
            if relative.is_absolute() or '..' in relative.parts or '\\' in name or ':' in name or relative.suffix not in ('.py','.js','.cjs','.md'):
                raise ValueError('Only explicitly reviewed source files may be exported: '+name)
            if set(p.lower() for p in relative.parts)&{'security','config','runtime','data','__pycache__'}:raise ValueError('Private path refused')
            target=(root/name).resolve()
            if not target.is_relative_to(root):raise ValueError('Source escapes root')
            blob=target.read_bytes()
            if not blob or len(blob)>2*1024*1024 or '\x00' in blob.decode('utf-8-sig'):raise ValueError('Invalid source file')
            if name in hashes:raise ValueError('Duplicate file')
            contents['src/'+name]=blob;hashes[name]=hashlib.sha256(blob).hexdigest()
        revision=hashlib.sha256(json.dumps({'files':hashes,'integration':item['integration'],**({'release':item['release']} if 'release' in item else {})},sort_keys=True,ensure_ascii=False).encode()).hexdigest()[:12]
        manifest={'schema':'daty-plugin-source-package-v1','id':identity,'name':item['name'],'brand':item['brand'],'adapterKeys':item['adapterKeys'],'sourceRevision':revision,'files':hashes,'integration':item['integration'],'installable':False}
        if 'release' in item:
            manifest.update(schema='daty-plugin-package-v1',installable=True,host_api=item['release']['host_api'],entrypoints=item['release']['entrypoints'])
        contents['manifest.json']=(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n').encode()
        contents['README.md']=(f"# {item['name']} 配接源码\n\n源码版本：{revision}。`src/` 内 {len(hashes)} 个文件与生成此导出包时的服务器源码逐字一致，SHA256 见 manifest.json。\n\n"
            "这是经平台可信整包目录审核后才能导入的配接包。改动源码后必须重新审核摘要；运行中的旧版本须停服维护升级。云端插件库尚未开放。\n\n"
            "## 接入\n\n"+item['integration']['notes']+"\n\n宿主装配、桥接入口和共享依赖见 manifest.json。保留现有配对/TLS、稳定身份、统一GROUP/CH、原命令日记及持久化；网页经MQTT读取状态，不能直接越过服务器控制设备。\n\n"
            "## 模块范围\n\n实际文件、能力键、运行入口、宿主依赖与兼容参考分类均见 manifest.json。现场机身标签注册表、已知设备缓存与安全配置不在导出包内；设备能力未知时不得猜测频段。\n\n"
            "## 验证与更新\n\n先做离线报文及隔离网络测试，再在授权范围内进行实机验收。未知值不补零；真实回读不冒充command_id ACK；未知/超时控制不得自动重放。修改源文件后重新生成导出目录并随正式包发布；新增品牌在contracts/brand-plugin-exports.json列出实际源码与能力键，再运行scripts/build-plugin-exports.py。\n\n"
            "本包不包含数据库、配对密钥、证书、现场配置、设备状态或遥测记录。DATY 自有源码采用 MIT；许可证见 src/licenses/DATY-LICENSE.md。RFutils 为设计参考，保留其 MIT 许可证及版权署名于 src/licenses/RFutils-LICENSE.md。参考与原创实现的范围见源码注释。\n").encode()
        output=io.BytesIO()
        with zipfile.ZipFile(output,'w',zipfile.ZIP_DEFLATED) as z:
            for name,blob in sorted(contents.items()):
                info=zipfile.ZipInfo(identity+'/'+name,(2026,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16
                z.writestr(info,blob)
        archive=output.getvalue()
        catalog.append({'id':identity,'name':item['name'],'brand':item['brand'],'adapterKeys':item['adapterKeys'],'revision':revision,'fileName':f'DATY-{identity}-{revision}.zip','sourceFiles':len(hashes),'bytes':len(archive),'sha256':hashlib.sha256(archive).hexdigest(),'base64':base64.b64encode(archive).decode()})
    return '/* Generated by scripts/build-plugin-exports.py. Do not hand-edit. */\nglobalThis.DatyPluginSourceCatalog = Object.freeze('+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+');\n'

def package_public(root, public, payload, check=False):
    """Fold source-only modules into the existing approved public discovery asset."""
    root,public=Path(root),Path(public)
    marker='/* DATY_PLUGIN_SOURCE_EXPORT_BEGIN */'
    end='/* DATY_PLUGIN_SOURCE_EXPORT_END */'
    p=public/'src/modules/discovery.js';body=p.read_bytes().decode('utf-8')
    block=marker+'\n'+'\n;\n'.join(((root/'src/platform/plugin-export-host.js').read_text('utf-8'),payload,(root/'src/modules/plugin-source-export.js').read_text('utf-8')))+'\n;\n'+end+'\n'
    if marker in body:
        if body.count(marker)!=1 or body.count(end)!=1:raise ValueError('Malformed export bundle')
        a=body.index(marker);b=body.index(end)+len(end)
        actual=body[a:b]+'\n'
        if check:
            if actual.replace('\r\n','\n')!=block:raise ValueError('Public export bundle is stale')
            return
        body=body[:a]+block+body[b:].lstrip('\n')
    elif check:raise ValueError('Missing public export bundle')
    else:body+='\n'+block
    newline='\r\n' if p.read_bytes().count(b'\r\n')==p.read_bytes().count(b'\n') else '\n'
    p.write_bytes(body.replace('\r\n','\n').replace('\n',newline).encode('utf-8'))
    html=public/'unirf-app.html';text=html.read_bytes().decode('utf-8')
    for name in ('src/platform/plugin-export-host.js','src/modules/plugin-source-catalog.js','src/modules/plugin-source-export.js'):
        text=re.sub(r'<script src="'+re.escape(name)+r'(?:\?v=[^"]*)?"></script>\s*','',text)
    html.write_bytes(text.encode('utf-8'))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--root',required=True);parser.add_argument('--registry',required=True);parser.add_argument('--output',required=True);parser.add_argument('--public');parser.add_argument('--check',action='store_true');a=parser.parse_args()
    text=build(a.root,a.registry);out=Path(a.output)
    if a.check:
        if out.read_text('utf-8')!=text:raise SystemExit('Plugin export catalog is stale; regenerate before release')
    else:
        out.parent.mkdir(parents=True,exist_ok=True);out.write_text(text,encoding='utf-8')
    if a.public:package_public(a.root,a.public,text,a.check)
    print(json.dumps({'checked':a.check,'catalogBytes':len(text.encode())}))
